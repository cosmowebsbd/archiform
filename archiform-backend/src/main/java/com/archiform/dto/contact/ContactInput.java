package com.archiform.dto.contact;
public class ContactInput {
    private String name, email, phone, company, city, country, notes;
    public String getName() { return name; } public void setName(String v) { name=v; }
    public String getEmail() { return email; } public void setEmail(String v) { email=v; }
    public String getPhone() { return phone; } public void setPhone(String v) { phone=v; }
    public String getCompany() { return company; } public void setCompany(String v) { company=v; }
    public String getCity() { return city; } public void setCity(String v) { city=v; }
    public String getCountry() { return country; } public void setCountry(String v) { country=v; }
    public String getNotes() { return notes; } public void setNotes(String v) { notes=v; }
}
